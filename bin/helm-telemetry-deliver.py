#!/usr/bin/env python3
"""helm-telemetry-deliver — deliver the ORIGINAL Brain Dashboard GUI to
Dither's codypc Desktop as brain-dashboard.html.

Why this exists (2026-11-12): the first telemetry face was a new plain
page (helm-telemetry.html). Dither ordered the telemetry to carry the
same GUI the daemon has always had — the suite's own Brain Dashboard
(~/.juno-brain/workspace/brain-dashboard.html, regenerated by the
suite's generate-dashboard.sh module scripts). This script ships THAT
file, unchanged, on the 5-minute cadence.

Transport (per codypc_remote_ops skill — the single-shot inline base64
used before got mangled in transit at least once, 2026-11-12 18:28):
chunked base64 over codypc-exec, every chunk's cumulative byte count
verified on the remote before the next is sent, assembled remotely,
sha256 verified against the source BEFORE the file is moved into
place, staging cleaned up after. Every remote command carries the
REAL_PC guard and aborts on mismatch.

Stdout: one line — OK + sha256 + byte count, or FAIL + reason.
Exit: 0 on verified delivery, 1 otherwise.
"""
import base64
import hashlib
import os
import re
import subprocess
import sys

HOME = os.path.expanduser("~")
SRC = os.path.join(HOME, ".juno-brain", "workspace", "brain-dashboard.html")
EXEC = os.path.join(HOME, "workspace", "bin", "codypc-exec")
GUARD = ('test "$(hostname)" = a1 && '
         'grep -q "Ryzen 7 3700X" /proc/cpuinfo && '
         'test -d /home/cody/Documents/nvr-emulator '
         '|| { echo GUARD_FAIL; exit 99; }; ')
STAGE = "/home/cody/Desktop/.brain-dashboard.b64"
DEST_TMP = "/home/cody/Desktop/.brain-dashboard.tmp.html"
DEST = "/home/cody/Desktop/brain-dashboard.html"
CHUNK = 8000


def run_remote(body, timeout=120):
    """Returns (rc, stdout, stderr) as SEPARATE streams.

    stdout and stderr must stay separate: over route 2 (juno-call)
    codypc-exec appends an "[exit N]" marker to stderr, and any
    bare-number parse over the combined streams picks up the marker's
    digit instead of the command's own output. That is exactly what
    happened 2026-11-23 04:07-04:41 UTC: route 1 died (proxy_closed
    on every CONNECT), every chunk-0 check ran over route 2, and the
    parse read "remote said 0" from "[exit 0]" while wc had actually
    printed 8000. Parse command output from stdout only.
    """
    p = subprocess.run([EXEC, GUARD + body], capture_output=True,
                       text=True, timeout=timeout)
    return p.returncode, (p.stdout or ""), (p.stderr or "")


def fail(msg):
    # Best-effort staging cleanup; the Desktop file itself is only ever
    # replaced by a hash-verified mv, so a failure leaves it untouched.
    try:
        run_remote(f"rm -f {STAGE} {DEST_TMP}", timeout=60)
    except Exception:
        pass
    print(f"FAIL {msg}")
    return 1


def main():
    try:
        with open(SRC, "rb") as f:
            data = f.read()
    except Exception as e:
        print(f"FAIL source unreadable: {e}")
        return 1
    sha = hashlib.sha256(data).hexdigest()
    b64 = base64.b64encode(data).decode("ascii")
    chunks = [b64[i:i + CHUNK] for i in range(0, len(b64), CHUNK)]

    sent = 0
    for i, ch in enumerate(chunks):
        op = ">" if i == 0 else ">>"
        try:
            rc, out, err = run_remote(
                f"printf %s '{ch}' {op} {STAGE}; wc -c < {STAGE}")
        except Exception as e:
            return fail(f"chunk {i}: exec error {e}")
        if rc != 0 or "GUARD_FAIL" in out:
            return fail(f"chunk {i}: rc={rc} "
                        f"out={out.strip()[-120:]} err={err.strip()[-120:]}")
        sent += len(ch)
        nums = re.findall(r"\d+", out)  # stdout only: see run_remote
        if not nums or int(nums[-1]) != sent:
            return fail(f"chunk {i}: staged byte count mismatch "
                        f"(expected {sent}, remote said "
                        f"{nums[-1] if nums else 'nothing'})")

    try:
        rc, out, err = run_remote(
            f"base64 -d {STAGE} > {DEST_TMP} && sha256sum {DEST_TMP}")
    except Exception as e:
        return fail(f"decode: exec error {e}")
    m = re.findall(r"\b[0-9a-f]{64}\b", out)
    if rc != 0 or not m or m[-1] != sha:
        return fail(f"decoded hash mismatch rc={rc} "
                    f"remote={m[-1] if m else 'none'} local={sha} "
                    f"err={err.strip()[-120:]}")

    try:
        rc, out, err = run_remote(
            f"mv {DEST_TMP} {DEST} && rm -f {STAGE} && sha256sum {DEST}")
    except Exception as e:
        return fail(f"install: exec error {e}")
    m = re.findall(r"\b[0-9a-f]{64}\b", out)
    if rc != 0 or not m or m[-1] != sha:
        return fail(f"installed hash mismatch rc={rc} "
                    f"err={err.strip()[-120:]}")
    print(f"OK {DEST} sha256={sha} bytes={len(data)} chunks={len(chunks)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
